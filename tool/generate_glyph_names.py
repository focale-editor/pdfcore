#!/usr/bin/env python3
"""Generate PdfCore's pinned AGL and PDF StandardEncoding tables (no network)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def literal(value):
    """Use Dart single quotes and escaped controls/directional Unicode scalars."""
    escaped = json.dumps(value, ensure_ascii=True)[1:-1].replace('\\"', '"')
    return "'" + escaped.replace("'", "\\'").replace('$', '\\$') + "'"


def main():
    entries = {}
    for line in (ROOT / 'tool/agl/glyphlist.txt').read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        name, scalars = line.split(';')
        entries[name] = ''.join(chr(int(scalar, 16)) for scalar in scalars.split())
    encoding = json.loads((ROOT / 'tool/agl/standard_encoding.json').read_text())
    assert len(encoding) == 256
    source = '// Generated by tool/generate_glyph_names.py. See THIRD_PARTY_NOTICES.md.\n\n'
    source += '/// Adobe glyph names with their defined Unicode sequences.\nconst Map<String, String> pdfGlyphNames = {\n'
    source += ''.join(f'  {literal(name)}: {literal(value)},\n' for name, value in entries.items())
    source += '};\n\n/// Adobe StandardEncoding from PDF 1.7, Annex D.\nconst List<String> pdfStandardEncoding = [\n'
    source += ''.join(f'  {literal(name)},\n' for name in encoding) + '];\n'
    (ROOT / 'lib/src/editing/pdf_glyph_names.dart').write_text(source)


if __name__ == '__main__':
    main()
