"""Regenerate original synthetic encryption fixtures using independent QPDF.

Requires pikepdf 10.18.1. No private artwork or third-party PDF corpus is used.
Generated bytes vary because encryption uses random salts and file identifiers.
"""
from pathlib import Path
import base64
import io
import json
import pikepdf

pdf = pikepdf.Pdf.new()
for index in range(2):
    page = pdf.add_blank_page(page_size=(200, 300))
    page.Contents = pdf.make_stream(b'q 1 0 0 rg 20 30 40 50 re f Q\n')
pdf.docinfo.Title = 'Encrypted synthetic document'
pdf.Root.Metadata = pdf.make_stream(b'<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"/></x:xmpmeta>')
pdf.Root.Metadata.Type = pikepdf.Name.Metadata
pdf.Root.Metadata.Subtype = pikepdf.Name.XML
fixtures = {}
for revision, aes in [(2, False), (3, False), (4, False), (4, True), (5, True), (6, True)]:
    for empty in [False, True]:
        for metadata in ([True, False] if aes else [False]):
            name = f'r{revision}-' + ('aes' if aes else 'rc4') + ('-empty' if empty else '') + ('-clear-metadata' if revision >= 4 and not metadata else '')
            user = '' if empty else 'lecture'
            stream = io.BytesIO()
            pdf.save(stream, encryption=pikepdf.Encryption(user=user, owner='proprietaire', R=revision, aes=aes, metadata=metadata), object_stream_mode=pikepdf.ObjectStreamMode.generate if revision >= 4 else pikepdf.ObjectStreamMode.disable, fix_metadata_version=False)
            fixtures[name] = {'revision': revision, 'user': user, 'owner': 'proprietaire', 'data': base64.b64encode(stream.getvalue()).decode()}
# A Dart literal keeps the same corpus available on VM and JavaScript/Node.
output = Path(__file__).resolve().parents[1] / 'test/fixtures/encrypted_pdfs.dart'
output.parent.mkdir(exist_ok=True)
output.write_text('/// Original QPDF-generated fixtures; see tool/generate_security_fixtures.py.\nconst Map<String, Map<String, Object>> encryptedPdfs = ' + json.dumps(fixtures, indent=2).replace(chr(34), chr(39)) + ';\n')
print(f'Generated {len(fixtures)} independent QPDF fixtures')
